/**
 * Точка входа в корне проекта — для развёртывания на хостингах, где нельзя
 * указать document root на подкаталог public/ (частая ситуация на shared
 * hosting с PHP без возможности задать отдельный веб-каталог).
 *
 * Это ТОЛЬКО тонкий шлюз: вся логика остаётся в public/index.php, здесь
 * ничего не дублируется. __DIR__ внутри требуемого файла разрешается
 * относительно ЕГО собственного расположения (public/), а не этого шлюза,
 * поэтому все относительные require/пути внутри работают без изменений.
 *
 * ВАЖНО (безопасность): если index.php в корне используется, весь остальной
 * код проекта (src/, var/, templates/, tests/, bin/, config/, .git/) физически
 * лежит рядом, в той же папке, что отдаёт веб-сервер. Эти каталоги НЕ должны
 * быть доступны по HTTP. См. .htaccess в корне проекта (для Apache/LiteSpeed)
 * и раздел README «Развёртывание с document root в корне проекта» — там же
 * описана конфигурация для nginx, где .htaccess не действует и нужен
 * отдельный блок location в конфиге сервера.
 */

require __DIR__ . '/public/index.php';
